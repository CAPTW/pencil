import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const source = readFileSync(new URL("../src/instantSelectionRuntime.ts", import.meta.url), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const m = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
const token = { sessionId: "mission", generation: 1 };
const candidate = { ...token, kind: "instant", text: "candidate" };
let state = m.captureReset(m.EMPTY_INSTANT_RUNTIME_STATE, token.sessionId, token.generation);
state = m.lateCandidate(state, candidate);
assert.ok(m.instantDraftProof(state, token, "source", "candidate"));
state = m.editDraft(state, "my edited draft");
const proof = m.instantDraftProof(state, token, "source", "my edited draft");
assert.equal(proof.userEdited, true); assert.equal(proof.draftRevision, 1);
assert.equal(proof.candidate, "candidate"); assert.equal(proof.source, "source");
assert.equal(m.instantDraftProof(state, { ...token, generation: 2 }, "source", state.draft), null);
assert.equal(m.instantDraftProof(state, token, "source", "untracked edit"), null);
const late = m.lateCandidate(state, { ...token, kind: "deep", text: "late deep" });
assert.equal(late.draft, "my edited draft"); assert.equal(late.draftOrigin, "instant");
assert.equal(m.requestSwitch(late, { ...candidate, generation: 2 }), late);
const reset = m.captureReset(late, "next", 2);
assert.equal(m.instantDraftProof(reset, token, "source", state.draft), null);
console.log("mission draft: actual production module assertions PASS");
